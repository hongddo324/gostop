const lastPick = new Map<string, number>();

/** 대사 한 줄 고르기 — 같은 상황에서 직전과 같은 대사는 피한다 */
export function line(
  seatId: string,
  key: LineKey,
  vars: Record<string, string | number> = {},
  rng: () => number = Math.random,
): string | undefined {
  const pool = DIALOGUE[seatId]?.[key];
  if (!pool || pool.length === 0) return undefined;
  const k = `${seatId}:${key}`;
  let i = Math.floor(rng() * pool.length);
  if (pool.length > 1 && i === lastPick.get(k)) i = (i + 1) % pool.length;
  lastPick.set(k, i);
  return pool[i]!.replace(/\{(\w+)\}/g, (_, v: string) => String(vars[v] ?? ''));
}
